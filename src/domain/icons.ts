function find(text: string): string | null {
  const t = text.toLowerCase().replace(/ё/g, 'е');
  for (const [keys, icon] of RULES) if (keys.some((k) => t.includes(k))) return icon;
  return null;
}

export function iconFor(subName: string, categoryName: string): string {
  return find(subName) ?? find(categoryName) ?? (subName || categoryName || '?').trim().charAt(0).toUpperCase();
}

/** Номер оттенка (1–6) для кружка категории — стабильный для одного и того же id. */
export function tintFor(id: string): number {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  return (h % 6) + 1;
}
